const textEntries = Object.entries(translations).sort(
    ([left], [right]) => right.length - left.length,
);

const translateValue = (value) =>
    textEntries.reduce(
        (result, [arabic, english]) => result.split(arabic).join(english),
        value,
    );

const translateNode = (node) => {
    if (node.nodeType === Node.TEXT_NODE) {
        const translated = translateValue(node.nodeValue);
        if (translated !== node.nodeValue) node.nodeValue = translated;
        return;
    }

    if (node.nodeType !== Node.ELEMENT_NODE) return;

    ["placeholder", "title", "aria-label"].forEach((attribute) => {
        const value = node.getAttribute(attribute);
        if (value) node.setAttribute(attribute, translateValue(value));
    });

    node.childNodes.forEach(translateNode);
};

export const startLocalization = (locale) => {
    if (locale !== "en") return;

    const translate = () => {
        translateNode(document.body);
        translateNode(document.head);
    };
    translate();

    const observer = new MutationObserver(translate);
    observer.observe(document.documentElement, {
        childList: true,
        subtree: true,
    });
};
